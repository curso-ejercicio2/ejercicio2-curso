def sumar(a, b):
    """
    Suma dos números.

    Args:
        a (float): Primer número
        b (float): Segundo número

    Returns:
        float: Resultado de a + b
    """
    return a + b


def suma_lista(lista):
    """
    Suma todos los elementos de una lista de números.

    Args:
        lista (list): Lista de números

    Returns:
        float: Suma total de los elementos
    """
    return sum(lista)